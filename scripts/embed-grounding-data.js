// C-2 staged grounding: regenerates the GROUNDING_DATA inline block inside
// api/generate.js from lib/belief-map-registry.js.
//
// api/generate.js has a zero-import containment contract (A0.1) - no
// module of any kind may be pulled in at runtime - so registry data it
// needs must live inline, exactly the way AXIS_LABELS / ARCHETYPE_REGISTRY
// already do. This script generates that inline copy from the canonical
// registry so the two cannot drift by hand-editing: per axis, only the
// compact fields the grounding selector needs (displayName as label,
// shortDefinition as def, and each band's `short` text - never the `full`
// texts, which would blow the prompt budget), plus the full glossary.
// api/generate.test.js's grounding section asserts byte parity of every
// carried field against lib/belief-map-registry.js.
//
// Run with:
//   node scripts/embed-grounding-data.js

'use strict';

const fs = require('fs');
const path = require('path');

const { BELIEF_MAP_REGISTRY, BAND_THRESHOLDS, BAND_KEYS, GLOSSARY } = require('../lib/belief-map-registry.js');

const BLOCK_START = '// GROUNDING_DATA block (auto-generated from lib/belief-map-registry.js, do not hand-edit)';
const BLOCK_END = '// END GROUNDING_DATA block';

const data = {};
Object.keys(BELIEF_MAP_REGISTRY).forEach((axisId) => {
  const e = BELIEF_MAP_REGISTRY[axisId];
  const bands = {};
  BAND_KEYS.forEach((band) => { bands[band] = e.bands[band].short; });
  data[axisId] = { label: e.displayName, def: e.shortDefinition, bands };
});

const body =
  `${BLOCK_START}\n` +
  `// C-2 staged grounding data (2026-08-02): the compact five-band evidence\n` +
  `// the grounding selector draws on - per axis, the display label, short\n` +
  `// definition, and each band's short interpretation text, plus the\n` +
  `// glossary. Generated by scripts/embed-grounding-data.js from the\n` +
  `// FC4-audited lib/belief-map-registry.js; never hand-edit here (DI-005).\n` +
  `// Band thresholds are carried alongside so classification stays single-\n` +
  `// sourced with the registry (parity-tested).\n` +
  `const GROUNDING_THRESHOLDS = ${JSON.stringify(BAND_THRESHOLDS)};\n` +
  `const GROUNDING_DATA = ${JSON.stringify(data, null, 1)};\n` +
  `const GROUNDING_GLOSSARY = ${JSON.stringify(GLOSSARY, null, 1)};\n` +
  `${BLOCK_END}`;

const genPath = path.join(__dirname, '..', 'api', 'generate.js');
let src = fs.readFileSync(genPath, 'utf8');

const startIdx = src.indexOf(BLOCK_START);
const endMarkerIdx = src.indexOf(BLOCK_END);

if (startIdx === -1 || endMarkerIdx === -1) {
  // First run: insert directly above the prompt builders, next to the
  // other inline registries.
  const anchor = 'function buildCall1Prompt(ctx) {';
  const anchorIdx = src.indexOf(anchor);
  if (anchorIdx === -1) throw new Error('anchor not found: buildCall1Prompt definition');
  src = src.slice(0, anchorIdx) + body + '\n\n' + src.slice(anchorIdx);
} else {
  const before = src.slice(0, startIdx);
  const after = src.slice(endMarkerIdx + BLOCK_END.length);
  src = before + body + after;
}

fs.writeFileSync(genPath, src, 'utf8');
const axisCount = Object.keys(data).length;
console.log(`Wrote GROUNDING_DATA block (${axisCount} axes, ${Object.keys(GLOSSARY).length} glossary terms) into api/generate.js`);
